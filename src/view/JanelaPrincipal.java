    private void cadastrarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cadastrarBtnActionPerformed
        // TODO add your handling code here:
        model.Games g = new model.Games();
        model.dao.GamesDAO gdao = new model.dao.GamesDAO();
        g.setNome(txtnome.getText());
        g.setSinopse(txtsinopse.getText());
        g.setDatalancamento(txtlancamento.getText());
        g.setPreco(Double.parseDouble(txtpreco.getText()));
        g.setPlataforma(txtplataforma.getText());
        g.setQuantidadesvendidas(Double.parseDouble(txtvenda.getText()));
        g.setCategoria(txtcategoria.getText());
        g.setDesenvolvedora(txtdev.getText());
        g.setNotametacritic(Double.parseDouble(txtnota.getText()));   
        try{
            gdao.cadastrar(g);
        }catch(SQLException | ClassNotFoundException ex){
            System.out.println("Erro...: " + ex.getMessage());
        }
        txtnome.setText("");
        txtsinopse.setText("");
        txtlancamento.setText("");
        txtpreco.setText("");
        txtplataforma.setText("");
        txtvenda.setText("");
        txtcategoria.setText("");
        txtdev.setText("");
        txtnota.setText("");
        sucessoLbl.setText("Cadastrado com Sucesso");
    }//GEN-LAST:event_cadastrarBtnActionPerformed

