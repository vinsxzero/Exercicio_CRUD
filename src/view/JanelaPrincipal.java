    private void ConsultarIdButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ConsultarIdButtonActionPerformed
        // TODO add your handling code here:
        model.Games g = new model.Games();
        model.dao.GamesDAO gdao = new model.dao.GamesDAO();
        g.setId(Integer.parseInt(txtidConsultarId.getText()));
        try{
            gdao.consultarById(g);
            if(g.getNome() != null){
            
            DefaultListModel modelolista = new DefaultListModel();
            modelolista.addElement("Id: " + g.getId());
            modelolista.addElement("Nome: "+g.getNome());
            modelolista.addElement("Sinopse: "+g.getSinopse());
            modelolista.addElement("Lançamento: " + g.getDatalancamento());
            modelolista.addElement("Preço"+ g.getPreco()); 
            modelolista.addElement("Plataforma: " + g.getPlataforma());
            modelolista.addElement("Vendas: " + g.getQuantidadesvendidas());
            modelolista.addElement("Categoria: " + g.getCategoria());
            modelolista.addElement("Desenvolvedora: " + g.getDesenvolvedora());
            modelolista.addElement("Nota MetaCritic: " + g.getNotametacritic());
            consultarList.setModel(modelolista);
            }else{
                LabelErro.setText("Id não encontrado");
                txtidConsultarId.setText("");
            }        
        }catch(SQLException | ClassNotFoundException ex){
            System.out.println("Erro: " + ex.getMessage());
        }
    }//GEN-LAST:event_ConsultarIdButtonActionPerformed

